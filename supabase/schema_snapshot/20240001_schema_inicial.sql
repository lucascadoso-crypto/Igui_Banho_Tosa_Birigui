-- ============================================================================
-- 7. usuarios_unidades
-- ============================================================================
-- Fonte de verdade para acesso por unidade/perfil (usada por is_master() e
-- can_access_unidade()). Um usuario auth pode ter varios vinculos, mas so
-- um ativo por vez (uq_usuarios_unidades_one_active_user).
create table if not exists public.usuarios_unidades (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  unidade_id bigint references public.unidades(id) on delete cascade,
  perfil public.user_profile not null default 'atendente',
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint usuarios_unidades_unidade_required_for_non_master
    check (perfil = 'master' or unidade_id is not null),
  constraint usuarios_unidades_unique_scope unique (user_id, unidade_id, perfil)
);


