-- ============================================================================
-- 1. unidades
-- ============================================================================
-- Lojas/unidades da rede. Tabela raiz: quase todas as outras tabelas
-- referenciam unidade_id para isolamento multi-unidade via RLS.
create table if not exists public.unidades (
  id bigint generated by default as identity primary key,
  nome text not null,
  slug text not null,
