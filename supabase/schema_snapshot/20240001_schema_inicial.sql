  constraint notas_fiscais_status_fase1_check check (status = 'RASCUNHO'),
  constraint notas_fiscais_valores_non_negative
    check (valor_servicos >= 0 and valor_desconto >= 0 and valor_total >= 0
      and valor_desconto <= valor_servicos and valor_total = (valor_servicos - valor_desconto))
);


