create or replace function public.is_master()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.funcionarios f
    where f.user_id = auth.uid()
      and f.ativo = true
      and f.cargo = 'master'
  );
$$;

create or replace function public.can_access_unidade(target_unidade_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_master()
    or exists (
      select 1
      from public.usuarios_unidades uu
      where uu.user_id = auth.uid()
        and uu.ativo = true
        and uu.unidade_id = target_unidade_id
    )
    or exists (
      select 1
      from public.funcionarios f
      where f.user_id = auth.uid()
        and f.ativo = true
        and f.unidade_id = target_unidade_id
    );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  is_first_user boolean;
  display_name text;
  initial_profile public.user_profile := 'atendente';
  initial_active boolean := false;
begin
  select not exists (select 1 from public.funcionarios) into is_first_user;

  if is_first_user then
    initial_profile := 'master';
    initial_active := true;
  end if;

  display_name := coalesce(
    new.raw_user_meta_data->>'nome',
    new.raw_user_meta_data->>'full_name',
    initcap(split_part(new.email, '@', 1)),
    'Novo Funcionario'
  );

  insert into public.funcionarios (user_id, nome, email, cargo, ativo)
  values (new.id, display_name, new.email, initial_profile, initial_active)
  on conflict (user_id) do update
  set email = excluded.email,
      nome = coalesce(public.funcionarios.nome, excluded.nome);

  if is_first_user then
    insert into public.usuarios_unidades (user_id, unidade_id, perfil, ativo)
    values (new.id, null, 'master', true)
    on conflict do nothing;
  end if;

  return new;
end;
$$;

