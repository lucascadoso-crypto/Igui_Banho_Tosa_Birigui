insert into public.funcionarios (
  user_id, unidade_id, nome, email, telefone, cargo, ativo, foto_url, created_at, updated_at
)
select
  f.user_id,
  mu.new_id,
  f.nome,
  f.email,
  f.telefone,
  case
    when f.cargo::text in ('master','admin_unidade','gerente','financeiro','atendente','tosador','somente_leitura')
      then f.cargo
    else 'atendente'::public.user_profile
  end,
  f.ativo,
  f.foto_url,
  f.created_at,
  f.updated_at
from _old_funcionarios f
left join _map_unidades mu on mu.old_id = f.unidade_id;

insert into public.funcionarios (user_id, nome, email, cargo, ativo)
select u.id, coalesce(u.raw_user_meta_data->>'nome', split_part(u.email, '@', 1)), u.email, 'master', true
from auth.users u
where not exists (select 1 from public.funcionarios f where f.user_id = u.id)
order by u.created_at
limit 1;

