  p_unidade_id bigint,
  p_acao text,
  p_tabela text,
  p_registro_id bigint,
  p_descricao text,
  p_dados_antes jsonb default null,
  p_dados_depois jsonb default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.auditoria_logs (
    unidade_id,
    user_id,
    acao,
    tabela,
    registro_id,
    descricao,
    dados_antes,
    dados_depois
  ) values (
    p_unidade_id,
    auth.uid(),
    p_acao,
    p_tabela,
    p_registro_id,
    p_descricao,
    p_dados_antes,
    p_dados_depois
  );
