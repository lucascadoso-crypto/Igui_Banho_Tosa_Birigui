  id bigint primary key generated by default as identity,
  unidade_id bigint not null references public.unidades(id) on delete restrict,
  agendamento_id bigint references public.agendamentos(id) on delete restrict,
  pacote_id bigint references public.pacotes(id) on delete restrict,
  financeiro_movimento_id bigint not null references public.financeiro_movimentos(id) on delete restrict,
  financeiro_pagamento_id bigint references public.financeiro_pagamentos(id) on delete restrict,
  cliente_id bigint not null references public.clientes(id) on delete restrict,
  status text not null default 'RASCUNHO',
  ambiente text not null default 'NAO_CONFIGURADO',
  tipo_documento text not null default 'NFS_E',
  numero_nota text,
  codigo_verificacao text,
  chave_acesso text,
  url_documento text,
  url_pdf text,
  xml_documento text,
  data_confirmacao_pagamento timestamptz not null,
  data_competencia date,
  data_emissao timestamptz,
  data_cancelamento timestamptz,
  valor_servicos numeric(10,2) not null default 0,
  valor_desconto numeric(10,2) not null default 0,
  valor_total numeric(10,2) not null default 0,
  descricao_servico text,
  observacoes_fiscais text,
  tomador_nome text,
  tomador_cpf_cnpj text,
  tomador_email text,
  tomador_telefone text,
  tomador_endereco text,
  mensagem_rejeicao text,
  resposta_integracao jsonb,
  criada_por_user_id uuid default auth.uid() references auth.users(id) on delete set null,
  atualizada_por_user_id uuid references auth.users(id) on delete set null,
  emitida_por_user_id uuid references auth.users(id) on delete set null,
  cancelada_por_user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint notas_fiscais_status_check check (status in (
    'RASCUNHO',
    'AGUARDANDO_CONFIGURACAO',
    'PRONTA_PARA_EMITIR',
    'EM_PROCESSAMENTO',
    'EMITIDA',
    'REJEITADA',
    'CANCELADA'
  )),
  constraint notas_fiscais_status_fase1_check check (status = 'RASCUNHO'),
  constraint notas_fiscais_origem_comercial_check check (
    (agendamento_id is not null and pacote_id is null)
    or (agendamento_id is null and pacote_id is not null)
  ),
  constraint notas_fiscais_valores_non_negative check (
    valor_servicos >= 0
    and valor_desconto >= 0
    and valor_total >= 0
    and valor_desconto <= valor_servicos
    and valor_total = valor_servicos - valor_desconto
  )
);

create table if not exists public.nota_fiscal_itens (
  id bigint primary key generated by default as identity,
  nota_fiscal_id bigint not null references public.notas_fiscais(id) on delete cascade,
  servico_id bigint references public.servicos(id) on delete set null,
  descricao text not null,
  observacoes_fiscais text,
  quantidade numeric(10,2) not null default 1,
  valor_unitario numeric(10,2) not null default 0,
  valor_desconto numeric(10,2) not null default 0,
  valor_total numeric(10,2) not null default 0,
  codigo_servico_municipal text,
  codigo_tributacao_nacional text,
  codigo_nbs text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint nota_fiscal_itens_valores_non_negative check (
    quantidade > 0
    and valor_unitario >= 0
    and valor_desconto >= 0
    and valor_total >= 0
    and valor_desconto <= (quantidade * valor_unitario)
    and valor_total = (quantidade * valor_unitario) - valor_desconto
  )
);

