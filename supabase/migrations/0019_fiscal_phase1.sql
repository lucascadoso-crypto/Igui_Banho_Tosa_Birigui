end;
$$;

create or replace function public.fiscal_validate_note_items_total(target_nota_fiscal_id bigint)
returns void
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  header_total numeric(10,2);
  items_total numeric(10,2);
begin
  select nf.valor_servicos into header_total
  from public.notas_fiscais nf
  where nf.id = target_nota_fiscal_id;

  if header_total is null then
    return;
  end if;

  select coalesce(sum(nfi.valor_total), 0)::numeric(10,2) into items_total
  from public.nota_fiscal_itens nfi
  where nfi.nota_fiscal_id = target_nota_fiscal_id;

  if items_total <> header_total then
    raise exception 'Total dos itens fiscais (%) difere do valor de servicos da nota fiscal (%)', items_total, header_total;
  end if;
end;
$$;

create or replace function public.fiscal_validate_note_items_total_trigger()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  target_id bigint;
begin
  target_id := coalesce(new.nota_fiscal_id, old.nota_fiscal_id);
  perform public.fiscal_validate_note_items_total(target_id);
  return coalesce(new, old);
end;
$$;

create or replace function public.fiscal_protect_nota_fiscal()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' then
    if old.status is distinct from 'RASCUNHO' then
      raise exception 'Somente rascunhos fiscais podem ser editados nesta fase.';
    end if;

    if (
      to_jsonb(new) - array[
        'data_competencia',
        'descricao_servico',
        'observacoes_fiscais',
        'tomador_nome',
        'tomador_cpf_cnpj',
        'tomador_email',
        'tomador_telefone',
        'tomador_endereco',
        'atualizada_por_user_id',
        'updated_at'
      ]::text[]
    ) <> (
      to_jsonb(old) - array[
        'data_competencia',
        'descricao_servico',
        'observacoes_fiscais',
        'tomador_nome',
        'tomador_cpf_cnpj',
        'tomador_email',
        'tomador_telefone',
        'tomador_endereco',
        'atualizada_por_user_id',
        'updated_at'
      ]::text[]
    ) then
      raise exception 'Somente data de competencia, descricao, observacoes fiscais e dados do tomador podem ser alterados no rascunho fiscal nesta fase.';
    end if;

    new.atualizada_por_user_id := auth.uid();

    perform public.fiscal_safe_audit(
      new.unidade_id,
      'EDICAO_RASCUNHO_FISCAL',
      'notas_fiscais',
      new.id,
      'Editou campos permitidos do rascunho fiscal #' || new.id::text || '.',
      jsonb_build_object(
        'data_competencia', old.data_competencia,
        'descricao_servico', old.descricao_servico,
        'observacoes_fiscais', old.observacoes_fiscais,
        'tomador_nome', old.tomador_nome,
        'tomador_email', old.tomador_email,
        'tomador_telefone', old.tomador_telefone,
        'tomador_endereco', old.tomador_endereco
      ),
      jsonb_build_object(
        'data_competencia', new.data_competencia,
        'descricao_servico', new.descricao_servico,
        'observacoes_fiscais', new.observacoes_fiscais,
        'tomador_nome', new.tomador_nome,
        'tomador_email', new.tomador_email,
        'tomador_telefone', new.tomador_telefone,
        'tomador_endereco', new.tomador_endereco
      )
    );
  end if;

  return new;
end;
$$;

create or replace function public.fiscal_protect_nota_fiscal_item()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  note_status text;
  note_unidade_id bigint;
begin
  select nf.status, nf.unidade_id
    into note_status, note_unidade_id
  from public.notas_fiscais nf
  where nf.id = coalesce(new.nota_fiscal_id, old.nota_fiscal_id);

  if note_status is distinct from 'RASCUNHO' then
    raise exception 'Itens fiscais so podem ser alterados enquanto a nota estiver em rascunho.';
  end if;

  if tg_op = 'UPDATE' then
    if old.nota_fiscal_id is distinct from new.nota_fiscal_id
      or old.servico_id is distinct from new.servico_id
      or old.quantidade is distinct from new.quantidade
      or old.valor_unitario is distinct from new.valor_unitario
      or old.valor_desconto is distinct from new.valor_desconto
      or old.valor_total is distinct from new.valor_total
      or old.codigo_servico_municipal is distinct from new.codigo_servico_municipal
      or old.codigo_tributacao_nacional is distinct from new.codigo_tributacao_nacional
      or old.codigo_nbs is distinct from new.codigo_nbs then
      raise exception 'Servico, valores e codigos fiscais dos itens nao podem ser alterados diretamente no rascunho fiscal.';
    end if;

    perform public.fiscal_safe_audit(
      note_unidade_id,
      'EDICAO_ITEM_RASCUNHO_FISCAL',
      'nota_fiscal_itens',
      new.id,
      'Editou descricao/observacoes permitidas do item fiscal #' || new.id::text || '.',
      jsonb_build_object('descricao', old.descricao, 'observacoes_fiscais', old.observacoes_fiscais),
      jsonb_build_object('descricao', new.descricao, 'observacoes_fiscais', new.observacoes_fiscais)
    );
  end if;

  return coalesce(new, old);
end;
$$;

create or replace function public.fiscal_audit_config_fiscal_unidade()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  target_row public.config_fiscal_unidade;
begin
  target_row := coalesce(new, old);

  perform public.fiscal_safe_audit(
    target_row.unidade_id,
    case
      when tg_op = 'INSERT' then 'CRIACAO_CONFIG_FISCAL'
      when tg_op = 'UPDATE' then 'EDICAO_CONFIG_FISCAL'
      else 'EXCLUSAO_CONFIG_FISCAL'
    end,
    'config_fiscal_unidade',
    target_row.id,
    case
      when tg_op = 'INSERT' then 'Criou configuracao fiscal da unidade.'
      when tg_op = 'UPDATE' then 'Editou configuracao fiscal da unidade.'
      else 'Excluiu configuracao fiscal da unidade.'
    end,
    case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) - 'cnpj' else null end,
    case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) - 'cnpj' else null end
  );

  return target_row;
end;
$$;

