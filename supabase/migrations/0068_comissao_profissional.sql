-- Financeiro (Prompt 2/4): Comissao por profissional.
--
-- Tabela nova aditiva (comissao_regras) + funcao de apuracao
-- (fn_comissoes_periodo), que le agendamentos.funcionario_id (ja existente
-- desde 0004_pacotes_agenda.sql) em atendimentos avulsos finalizados. Base
-- da comissao = valor_servico (mesma definicao de fn_receita_eventos, sem
-- taxi). Regra vigente na data do atendimento, prioridade: regra especifica
-- do funcionario+categoria > regra do funcionario (categoria 'todas') >
-- regra padrao da unidade (funcionario_id null) por categoria > padrao da
-- unidade (categoria 'todas'). Pacotes/adicionais nao entram agora (o pacote
-- nao tem funcionario_id por sessao de forma confiavel) -- fica para uma
-- extensao futura, sem quebrar o que ja existe aqui.

-- ---------------------------------------------------------------------------
-- 1) Regras de comissao
-- ---------------------------------------------------------------------------
create table if not exists public.comissao_regras (
  id bigint primary key generated by default as identity,
  unidade_id bigint not null references public.unidades(id) on delete restrict,
  funcionario_id bigint references public.funcionarios(id) on delete cascade,
  categoria_servico text not null default 'todas' check (categoria_servico in ('todas', 'banho', 'tosa', 'outro')),
  tipo text not null check (tipo in ('percentual', 'fixo')),
  valor numeric(10,2) not null default 0 check (valor >= 0),
  vigente_desde date not null default current_date,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_comissao_regras_busca
  on public.comissao_regras(unidade_id, funcionario_id, categoria_servico, vigente_desde desc);

create trigger set_comissao_regras_updated_at
before update on public.comissao_regras
for each row execute function public.set_updated_at();

alter table public.comissao_regras enable row level security;

grant select, insert, update, delete on public.comissao_regras to authenticated;
grant select, insert, update, delete on public.comissao_regras to service_role;
grant usage, select on sequence public.comissao_regras_id_seq to authenticated;

-- Leitura liberada para quem acessa a unidade; escrita restrita a master
-- (mesmo padrao de rentabilidade_config/servico_custo_historico, migration 0035).
create policy "comissao_regras_read_unit_access"
on public.comissao_regras for select to authenticated
using (public.can_access_unidade(unidade_id));

create policy "comissao_regras_master_write"
on public.comissao_regras for all to authenticated
using (public.is_master()) with check (public.is_master());

-- ---------------------------------------------------------------------------
-- 2) Apuracao do periodo
-- ---------------------------------------------------------------------------
create or replace function public.fn_comissoes_periodo(
  p_unidade_id bigint,
  p_data_inicio date,
  p_data_fim date
)
returns table (
  funcionario_id bigint,
  funcionario_nome text,
  agendamento_id bigint,
  pet_nome text,
  data_atendimento date,
  categoria text,
  valor_servico numeric,
  tipo_regra text,
  valor_regra numeric,
  valor_comissao numeric
)
language sql
stable
as $$
  with atendimentos as (
    select
      a.id as agendamento_id,
      a.unidade_id,
      a.funcionario_id,
      coalesce(a.data_fim_real::date, a.data_agendamento) as data_atendimento,
      public.fn_categoria_agendamento(a.id) as categoria,
      (coalesce(a.valor_total, 0) + coalesce(a.valor_pagamento_2, 0) - coalesce(a.valor_transporte, 0)) as valor_servico
    from public.agendamentos a
    where a.funcionario_id is not null
      and a.status = 'Finalizado'
      and a.pacote_id is null
      and (p_unidade_id is null or a.unidade_id = p_unidade_id)
      and coalesce(a.data_fim_real::date, a.data_agendamento) between p_data_inicio and p_data_fim
  ),
  regra_aplicavel as (
    select
      ev.*,
      (
        select cr.id
        from public.comissao_regras cr
        where cr.unidade_id = ev.unidade_id
          and cr.ativo = true
          and cr.vigente_desde <= ev.data_atendimento
          and (cr.funcionario_id = ev.funcionario_id or cr.funcionario_id is null)
          and (cr.categoria_servico = ev.categoria or cr.categoria_servico = 'todas')
        order by
          (cr.funcionario_id is not null) desc,
          (cr.categoria_servico <> 'todas') desc,
          cr.vigente_desde desc
        limit 1
      ) as regra_id
    from atendimentos ev
  )
  select
    ra.funcionario_id,
    f.nome as funcionario_nome,
    ra.agendamento_id,
    p.nome as pet_nome,
    ra.data_atendimento,
    ra.categoria,
    ra.valor_servico,
    cr.tipo as tipo_regra,
    cr.valor as valor_regra,
    case
      when cr.tipo = 'percentual' then round(ra.valor_servico * cr.valor / 100, 2)
      when cr.tipo = 'fixo' then cr.valor
      else 0
    end as valor_comissao
  from regra_aplicavel ra
  join public.funcionarios f on f.id = ra.funcionario_id
  left join public.agendamentos a2 on a2.id = ra.agendamento_id
  left join public.pets p on p.id = a2.pet_id
  left join public.comissao_regras cr on cr.id = ra.regra_id
  order by f.nome, ra.data_atendimento;
$$;

comment on function public.fn_comissoes_periodo(bigint, date, date) is
  'Apuracao de comissao por profissional no periodo: atendimentos avulsos finalizados com funcionario_id, aplicando a regra de comissao_regras vigente na data (mais especifica primeiro: funcionario > categoria > padrao da unidade). So cobre atendimentos avulsos por agora.';
