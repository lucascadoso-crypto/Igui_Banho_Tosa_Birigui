-- Dashboard Gerencial (Prompt 3/4): ocupação/capacidade + KPIs complementares
-- + rankings. Migration aditiva: nenhuma tabela/função existente é alterada
-- de forma destrutiva; o Dashboard atual (migration 0032) continua intacto.
--
-- ---------------------------------------------------------------------------
-- 1) Capacidade de atendimentos por unidade/dia da semana
-- ---------------------------------------------------------------------------
create table if not exists public.unidade_capacidade (
  id bigint primary key generated by default as identity,
  unidade_id bigint not null references public.unidades(id) on delete cascade,
  dia_semana integer not null check (dia_semana between 0 and 6), -- 0=domingo..6=sábado (mesma convenção de pacotes.dia_semana_preferido, migration 0051)
  capacidade integer not null default 0 check (capacidade >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (unidade_id, dia_semana)
);

comment on table public.unidade_capacidade is
  'Capacidade de atendimentos por dia da semana, por unidade. Configurado em Configurações (master). Usado no cálculo de ocupação do Dashboard Gerencial e no indicador "Cap · Disp · Ocup · %" da Agenda.';

create trigger set_unidade_capacidade_updated_at
before update on public.unidade_capacidade
for each row execute function public.set_updated_at();

alter table public.unidade_capacidade enable row level security;

grant select, insert, update, delete on public.unidade_capacidade to authenticated;
grant select, insert, update, delete on public.unidade_capacidade to service_role;
grant usage, select on sequence public.unidade_capacidade_id_seq to authenticated;

create policy "unidade_capacidade_read_unit_access"
on public.unidade_capacidade for select to authenticated
using (public.can_access_unidade(unidade_id));

create policy "unidade_capacidade_master_write"
on public.unidade_capacidade for all to authenticated
using (public.is_master()) with check (public.is_master());

-- ---------------------------------------------------------------------------
-- 2) Ocupação por dia da semana no período (gráfico + base da taxa de ocupação)
--    Uma linha por dia-da-semana presente no período, com a capacidade
--    somada de todos os dias daquele dia-da-semana (capacidade_dia × quantas
--    vezes aquele dia-da-semana ocorre no período).
-- ---------------------------------------------------------------------------
create or replace function public.fn_dashboard_ocupacao_periodo(
  p_unidade_id bigint,
  p_data_inicio date,
  p_data_fim date
)
returns table (
  dia_semana int,
  capacidade_dia int,
  dias_no_periodo int,
  capacidade_total int,
  agendados int,
  percentual numeric
)
language sql
stable
as $$
  with dias as (
    select extract(dow from d)::int as dow
    from generate_series(p_data_inicio, p_data_fim, interval '1 day') d
  ),
  contagem_dias as (
    select dow, count(*) as dias_no_periodo
    from dias
    group by dow
  ),
  cap as (
    select dia_semana, coalesce(sum(capacidade), 0) as capacidade_dia
    from public.unidade_capacidade
    where p_unidade_id is null or unidade_id = p_unidade_id
    group by dia_semana
  ),
  ag as (
    select extract(dow from a.data_agendamento)::int as dow, count(*) as agendados
    from public.agendamentos a
    where a.status <> 'Cancelado'
      and (p_unidade_id is null or a.unidade_id = p_unidade_id)
      and a.data_agendamento between p_data_inicio and p_data_fim
    group by 1
  )
  select
    cd.dow as dia_semana,
    coalesce(cap.capacidade_dia, 0) as capacidade_dia,
    cd.dias_no_periodo,
    coalesce(cap.capacidade_dia, 0) * cd.dias_no_periodo as capacidade_total,
    coalesce(ag.agendados, 0) as agendados,
    case when coalesce(cap.capacidade_dia, 0) * cd.dias_no_periodo > 0
      then round(coalesce(ag.agendados, 0)::numeric / (cap.capacidade_dia * cd.dias_no_periodo) * 100, 1)
      else 0
    end as percentual
  from contagem_dias cd
  left join cap on cap.dia_semana = cd.dow
  left join ag on ag.dow = cd.dow
  order by cd.dow;
$$;

comment on function public.fn_dashboard_ocupacao_periodo(bigint, date, date) is
  'Ocupação por dia da semana no período (capacidade × nº de ocorrências do dia-da-semana no período vs. agendamentos não cancelados). Chamada com p_data_inicio = p_data_fim dá a ocupação de um único dia (usada no indicador "Cap · Disp · Ocup · %" da Agenda).';

-- ---------------------------------------------------------------------------
-- 3) KPIs complementares: ticket médio e total a receber (atual + anterior)
--    Taxa de ocupação e taxa de no-show/cancelamento são derivadas no
--    frontend a partir de fn_dashboard_ocupacao_periodo e
--    fn_dashboard_agendamentos_cards (já existentes) — sem duplicar cálculo.
-- ---------------------------------------------------------------------------
create or replace function public.fn_dashboard_kpis_complementares(
  p_unidade_id bigint,
  p_data_inicio date,
  p_data_fim date,
  p_data_inicio_ant date,
  p_data_fim_ant date,
  p_transporte text default 'todos'
)
returns jsonb
language plpgsql
stable
as $$
declare
  v_fat_atual numeric;
  v_qtd_atual bigint;
  v_fat_ant numeric;
  v_qtd_ant bigint;
  v_a_receber_atual numeric;
  v_a_receber_ant numeric;
begin
  select coalesce(sum(valor_servico + valor_transporte), 0), count(*)
    into v_fat_atual, v_qtd_atual
  from public.fn_receita_eventos(p_unidade_id, p_data_inicio, p_data_fim, p_transporte);

  select coalesce(sum(valor_servico + valor_transporte), 0), count(*)
    into v_fat_ant, v_qtd_ant
  from public.fn_receita_eventos(p_unidade_id, p_data_inicio_ant, p_data_fim_ant, p_transporte);

  select coalesce((public.fn_financeiro_contas_pendentes_valor(p_unidade_id, p_data_inicio, p_data_fim, p_transporte, 'todos', 'todas') ->> 'a_receber_periodo')::numeric, 0)
    into v_a_receber_atual;

  select coalesce((public.fn_financeiro_contas_pendentes_valor(p_unidade_id, p_data_inicio_ant, p_data_fim_ant, p_transporte, 'todos', 'todas') ->> 'a_receber_periodo')::numeric, 0)
    into v_a_receber_ant;

  return jsonb_build_object(
    'ticket_medio_atual', case when v_qtd_atual > 0 then round(v_fat_atual / v_qtd_atual, 2) else 0 end,
    'ticket_medio_anterior', case when v_qtd_ant > 0 then round(v_fat_ant / v_qtd_ant, 2) else 0 end,
    'total_a_receber_atual', v_a_receber_atual,
    'total_a_receber_anterior', v_a_receber_ant
  );
end;
$$;

comment on function public.fn_dashboard_kpis_complementares(bigint, date, date, date, date, text) is
  'Ticket médio (fn_receita_eventos) e total a receber (fn_financeiro_contas_pendentes_valor, migration 0034) do período atual e anterior, para os KPIs novos do Dashboard Gerencial.';

-- ---------------------------------------------------------------------------
-- 4) Ranking: top clientes por faturamento e top raças atendidas
-- ---------------------------------------------------------------------------
create or replace function public.fn_dashboard_top_clientes(
  p_unidade_id bigint,
  p_data_inicio date,
  p_data_fim date,
  p_transporte text default 'todos',
  p_limite int default 10
)
returns table (cliente_id bigint, cliente_nome text, qtd_eventos bigint, faturamento numeric)
language sql
stable
as $$
  select
    ev.cliente_id,
    c.nome as cliente_nome,
    count(*) as qtd_eventos,
    sum(ev.valor_servico + ev.valor_transporte) as faturamento
  from public.fn_receita_eventos(p_unidade_id, p_data_inicio, p_data_fim, p_transporte) ev
  join public.clientes c on c.id = ev.cliente_id
  group by ev.cliente_id, c.nome
  order by faturamento desc
  limit p_limite;
$$;

comment on function public.fn_dashboard_top_clientes(bigint, date, date, text, int) is
  'Top clientes por faturamento no período (fn_receita_eventos). Usada no ranking do Dashboard (limite 10) e no relatório "Por cliente" (limite maior).';

create or replace function public.fn_dashboard_top_racas(
  p_unidade_id bigint,
  p_data_inicio date,
  p_data_fim date,
  p_limite int default 10
)
returns table (raca text, qtd bigint)
language sql
stable
as $$
  select coalesce(nullif(trim(p.raca), ''), 'Não informada') as raca, count(*) as qtd
  from public.agendamentos a
  join public.pets p on p.id = a.pet_id
  where a.status = 'Finalizado'
    and a.data_fim_real is not null
    and (p_unidade_id is null or a.unidade_id = p_unidade_id)
    and ((a.data_fim_real at time zone 'America/Sao_Paulo')::date) between p_data_inicio and p_data_fim
  group by 1
  order by qtd desc
  limit p_limite;
$$;

comment on function public.fn_dashboard_top_racas(bigint, date, date, int) is
  'Top raças de pets atendidos (atendimentos finalizados) no período, pela data de finalização.';
