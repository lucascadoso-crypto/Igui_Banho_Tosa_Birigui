-- Financeiro (Prompt 2/4): Fechamento de caixa do dia.
--
-- Tabela nova aditiva. Nao altera a "Conferencia de Entradas/Saidas" nem o
-- "Balanco de Auditoria" ja existentes em Financeiro.tsx -- esse fechamento
-- e um resumo adicional por forma de pagamento (Pix/Dinheiro/Debito/
-- Credito), com o valor esperado (calculado) e o valor conferido (contado
-- fisicamente), guardando quem fechou e quando.

create table if not exists public.caixa_fechamentos (
  id bigint primary key generated by default as identity,
  unidade_id bigint not null references public.unidades(id) on delete restrict,
  data_fechamento date not null,
  pix_esperado numeric(10,2) not null default 0,
  pix_conferido numeric(10,2) not null default 0,
  dinheiro_esperado numeric(10,2) not null default 0,
  dinheiro_conferido numeric(10,2) not null default 0,
  debito_esperado numeric(10,2) not null default 0,
  debito_conferido numeric(10,2) not null default 0,
  credito_esperado numeric(10,2) not null default 0,
  credito_conferido numeric(10,2) not null default 0,
  diferenca_total numeric(10,2) not null default 0,
  observacao text,
  fechado_por_user_id uuid references auth.users(id) on delete set null,
  fechado_por_nome text,
  fechado_em timestamptz not null default now(),
  constraint caixa_fechamentos_unidade_data_unico unique (unidade_id, data_fechamento)
);

create index if not exists idx_caixa_fechamentos_unidade_data
  on public.caixa_fechamentos(unidade_id, data_fechamento desc);

alter table public.caixa_fechamentos enable row level security;

grant select, insert, update on public.caixa_fechamentos to authenticated;
grant select, insert, update, delete on public.caixa_fechamentos to service_role;
grant usage, select on sequence public.caixa_fechamentos_id_seq to authenticated;

create policy "caixa_fechamentos_unit_access"
on public.caixa_fechamentos for all to authenticated
using (public.can_access_unidade(unidade_id)) with check (public.can_access_unidade(unidade_id));

comment on table public.caixa_fechamentos is
  'Fechamento de caixa do dia por forma de pagamento (esperado x conferido), registrado a partir de Financeiro.tsx. Nao substitui nem altera a conferencia/balanco de auditoria existentes -- e um resumo adicional.';
