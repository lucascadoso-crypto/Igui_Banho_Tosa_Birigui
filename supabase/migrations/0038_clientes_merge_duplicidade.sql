create table if not exists public.clientes_merge_log (
  id bigint primary key generated by default as identity,
  cliente_id bigint not null references public.clientes(id) on delete cascade,
  unidade_id bigint not null references public.unidades(id) on delete cascade,
  origem text not null default 'cadastro_publico',
  cliente_removido_id bigint references public.clientes(id) on delete set null,
  campos_alterados jsonb not null default '{}'::jsonb,
  executado_por_user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists idx_clientes_merge_log_cliente on public.clientes_merge_log(cliente_id);
create index if not exists idx_clientes_duplicados_pendentes_status on public.clientes_duplicados_pendentes(status);
create index if not exists idx_clientes_duplicados_pendentes_unidade on public.clientes_duplicados_pendentes(unidade_id);

-- Gera as variacoes plausiveis de um telefone brasileiro a partir dos digitos
-- puros: com/sem DDD, com/sem 9o digito extra do celular. Comparar por
-- sobreposicao (&&) em vez de igualdade estrita cobre casos como
-- "(18) 99651-5957" = "18996515957" = "996515957".
create or replace function public.telefone_variantes(p_telefone text)
returns text[]
language plpgsql
immutable
as $$
declare
  v_digits text;
  v_sem_ddd text;
  v_variantes text[] := array[]::text[];
begin
  v_digits := regexp_replace(coalesce(p_telefone, ''), '\D', '', 'g');

  if length(v_digits) < 8 then
    return v_variantes;
  end if;

  -- numero completo com DDD (10 ou 11 digitos)
  if length(v_digits) in (10, 11) then
    v_variantes := array_append(v_variantes, v_digits);

    -- alterna com/sem o 9o digito do celular, mantendo o DDD
    if length(v_digits) = 11 then
      v_variantes := array_append(v_variantes, substr(v_digits, 1, 2) || substr(v_digits, 4));
    else
      v_variantes := array_append(v_variantes, substr(v_digits, 1, 2) || '9' || substr(v_digits, 3));
    end if;
  else
    v_variantes := array_append(v_variantes, v_digits);
  end if;

  -- numero sem DDD (8 ou 9 digitos finais), para casar com cadastros antigos
  -- que foram salvos sem o codigo de area
  if length(v_digits) >= 10 then
    v_sem_ddd := substr(v_digits, 3);
  else
    v_sem_ddd := v_digits;
  end if;

  if length(v_sem_ddd) = 9 then
    v_variantes := array_append(v_variantes, v_sem_ddd);
    v_variantes := array_append(v_variantes, substr(v_sem_ddd, 2));
  elsif length(v_sem_ddd) = 8 then
    v_variantes := array_append(v_variantes, v_sem_ddd);
    v_variantes := array_append(v_variantes, '9' || v_sem_ddd);
  else
    v_variantes := array_append(v_variantes, v_sem_ddd);
  end if;

  return (select array_agg(distinct v) from unnest(v_variantes) v where v <> '');
end;
$$;

