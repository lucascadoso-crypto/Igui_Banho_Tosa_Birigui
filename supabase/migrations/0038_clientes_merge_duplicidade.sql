-- Merge de clientes vindos do link publico de auto-cadastro com clientes ja
-- existentes. Aditiva: so adiciona colunas/tabelas/funcoes novas, nenhum drop
-- de dado. Objetivo:
--   1. cadastro_publico_tutor_pets passa a casar telefone tolerando variacoes
--      (com/sem DDD, com/sem 9o digito) e nunca apaga campo bom com vazio.
--   2. Nome parecido mas telefone diferente NUNCA mescla sozinho: vai para a
--      fila clientes_duplicados_pendentes para revisao manual.
--   3. Todo merge grava diff antes/depois em clientes_merge_log (auditoria e
--      possibilidade de reversao).
--   4. mesclar_clientes/rejeitar_duplicado_cliente atendem os botoes da tela
--      de revisao; detectar_duplicados_retroativos so povoa a fila (nunca
--      mescla sozinha) para os duplicados que ja existem hoje.

begin;

create extension if not exists pg_trgm;

alter table public.clientes
  add column if not exists mesclado_no_cliente_id bigint references public.clientes(id) on delete set null;

create index if not exists idx_clientes_mesclado_no_cliente_id
  on public.clientes(mesclado_no_cliente_id)
  where mesclado_no_cliente_id is not null;

create table if not exists public.clientes_duplicados_pendentes (
  id bigint primary key generated by default as identity,
  cliente_id_existente bigint not null references public.clientes(id) on delete cascade,
  cliente_id_novo bigint not null references public.clientes(id) on delete cascade,
  unidade_id bigint not null references public.unidades(id) on delete cascade,
  motivo text not null,
  similaridade numeric(4,3),
  status text not null default 'pendente',
  resolvido_por_user_id uuid references auth.users(id) on delete set null,
  resolvido_em timestamptz,
  created_at timestamptz not null default now(),
  constraint clientes_duplicados_pendentes_status_check check (status in ('pendente', 'mesclado', 'rejeitado')),
  constraint clientes_duplicados_pendentes_diferentes check (cliente_id_existente <> cliente_id_novo)
);

create unique index if not exists uq_clientes_duplicados_pendentes_par_ativo
on public.clientes_duplicados_pendentes(cliente_id_existente, cliente_id_novo)
