on public.clientes_merge_log for select to authenticated
using (public.is_master() or public.can_access_unidade(unidade_id));

-- Status da fila de revisao so muda via mesclar_clientes/rejeitar_duplicado_cliente
-- (security definer): nenhuma escrita direta de authenticated na tabela.
grant select on public.clientes_duplicados_pendentes to authenticated;
revoke insert, update, delete on public.clientes_duplicados_pendentes from authenticated;
grant select on public.clientes_merge_log to authenticated;
revoke insert, update, delete on public.clientes_merge_log from authenticated;

revoke execute on function public.registrar_merge_cliente(bigint, bigint, text, jsonb, bigint) from public;
revoke execute on function public.mesclar_clientes(bigint, bigint) from public, anon;
revoke execute on function public.rejeitar_duplicado_cliente(bigint) from public, anon;
revoke execute on function public.detectar_duplicados_retroativos() from public, anon;
grant execute on function public.mesclar_clientes(bigint, bigint) to authenticated;
grant execute on function public.rejeitar_duplicado_cliente(bigint) to authenticated;
grant execute on function public.detectar_duplicados_retroativos() to authenticated;

commit;
