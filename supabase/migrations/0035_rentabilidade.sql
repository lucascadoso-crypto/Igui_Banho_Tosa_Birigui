-- Modulo de Rentabilidade (markup e margem por servico e pacote).
-- Migration aditiva: nenhuma tabela/coluna existente e alterada de forma
-- destrutiva. servicos.custo_padrao permanece como esta (vira apenas um
-- cache do custo vigente, mantido por trigger) para nao quebrar nada que
-- ja leia essa coluna.
--
-- Fonte unica de custo a partir de agora: servico_custo_historico (custo
-- por servico, versionado por data) e custo_transporte_historico (custo
-- por viagem de taxi dog, versionado por data). fn_dashboard_custos_pacotes
-- (migration 0032) e reescrita no fim deste arquivo para ler dessa mesma
-- fonte, eliminando a divergencia entre Dashboard e Rentabilidade.

-- ---------------------------------------------------------------------------
-- 1) Historico de custo por servico
-- ---------------------------------------------------------------------------
create table if not exists public.servico_custo_historico (
  id bigint primary key generated by default as identity,
  servico_id bigint not null references public.servicos(id) on delete cascade,
  custo_insumos numeric(10,2),
  custo_mao_obra numeric(10,2),
  custo_outros numeric(10,2),
  custo_total numeric(10,2) not null,
  vigente_desde date not null default current_date,
  observacao text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references auth.users(id) on delete set null
);

create index if not exists idx_servico_custo_historico_servico_data
  on public.servico_custo_historico(servico_id, vigente_desde desc);

-- Backfill: 1 registro por servico existente, vigente desde uma data
-- bem antiga, usando o custo_padrao atual (garante que fn_custo_servico_em
-- nunca retorna null para servicos ja cadastrados).
insert into public.servico_custo_historico (servico_id, custo_total, vigente_desde, observacao)
select s.id, coalesce(s.custo_padrao, 0), date '2000-01-01', 'Backfill automatico da migration 0035'
from public.servicos s
where not exists (
  select 1 from public.servico_custo_historico h where h.servico_id = s.id
);

-- ---------------------------------------------------------------------------
-- 2) Historico de custo de transporte/taxi dog (por viagem)
-- ---------------------------------------------------------------------------
create table if not exists public.custo_transporte_historico (
  id bigint primary key generated by default as identity,
  custo_combustivel numeric(10,2),
  custo_tempo numeric(10,2),
  custo_total numeric(10,2) not null,
  vigente_desde date not null default current_date,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references auth.users(id) on delete set null
);

create index if not exists idx_custo_transporte_historico_data
  on public.custo_transporte_historico(vigente_desde desc);

insert into public.custo_transporte_historico (custo_total, vigente_desde)
select 0, date '2000-01-01'
where not exists (select 1 from public.custo_transporte_historico);

-- ---------------------------------------------------------------------------
-- 3) Thresholds de margem (linha unica, mesmo padrao de config_sistema)
-- ---------------------------------------------------------------------------
create table if not exists public.rentabilidade_config (
  id bigint primary key default 1,
  margem_verde_min numeric(5,2) not null default 60,
  margem_amarela_min numeric(5,2) not null default 30,
  updated_at timestamptz not null default now(),
  constraint rentabilidade_config_singleton check (id = 1)
);

insert into public.rentabilidade_config (id)
select 1
where not exists (select 1 from public.rentabilidade_config where id = 1);

-- ---------------------------------------------------------------------------
-- 4) custo_padrao vira cache do custo vigente (compat. com codigo legado
--    que ainda leia essa coluna diretamente).
-- ---------------------------------------------------------------------------
create or replace function public.fn_sync_custo_padrao()
returns trigger
language plpgsql
as $$
begin
  update public.servicos
  set custo_padrao = coalesce((
    select h.custo_total
    from public.servico_custo_historico h
    where h.servico_id = new.servico_id
      and h.vigente_desde <= current_date
    order by h.vigente_desde desc
    limit 1
  ), 0)
  where id = new.servico_id;
  return new;
end;
$$;

drop trigger if exists trg_sync_custo_padrao on public.servico_custo_historico;
create trigger trg_sync_custo_padrao
after insert on public.servico_custo_historico
for each row execute function public.fn_sync_custo_padrao();

-- ---------------------------------------------------------------------------
-- 5) Helpers de leitura: custo vigente numa data (usa sempre a ultima linha
--    com vigente_desde <= data do evento, para relatorios antigos nao
--    mudarem retroativamente quando o custo atual e alterado).
-- ---------------------------------------------------------------------------
create or replace function public.fn_custo_servico_em(p_servico_id bigint, p_data date)
returns numeric
language sql
stable
as $$
  select coalesce(
    (
      select h.custo_total
      from public.servico_custo_historico h
      where h.servico_id = p_servico_id
        and h.vigente_desde <= coalesce(p_data, current_date)
      order by h.vigente_desde desc
      limit 1
    ),
    0
  );
$$;

create or replace function public.fn_custo_transporte_em(p_data date)
returns numeric
language sql
stable
as $$
  select coalesce(
    (
      select h.custo_total
      from public.custo_transporte_historico h
      where h.vigente_desde <= coalesce(p_data, current_date)
      order by h.vigente_desde desc
      limit 1
    ),
    0
  );
$$;

