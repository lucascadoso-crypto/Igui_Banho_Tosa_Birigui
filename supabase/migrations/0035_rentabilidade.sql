create policy "rentabilidade_config_master_write"
on public.rentabilidade_config for all to authenticated
using (public.is_master()) with check (public.is_master());

-- ---------------------------------------------------------------------------
-- 7) fn_dashboard_custos_pacotes (migration 0032) reescrita para usar a
--    fonte unica de custo (fn_custo_servico_em) em vez de custo_padrao
--    direto. Mesma assinatura e mesmas colunas de retorno: zero mudanca no
--    frontend do Dashboard (services/dashboardGerencial.ts), so a fonte do
--    dado por tras muda.
-- ---------------------------------------------------------------------------
create or replace function public.fn_dashboard_custos_pacotes(
  p_unidade_id bigint,
  p_data_inicio date,
  p_data_fim date,
  p_transporte text default 'todos'
)
returns table (servico text, qtd bigint, custo_unitario numeric, custo_total numeric)
language sql
stable
as $$
  with itens as (
    select
      s.nome as servico,
      public.fn_custo_servico_em(s.id, (a.data_fim_real at time zone 'America/Sao_Paulo')::date) as custo
    from public.agendamentos a
    join public.agendamento_itens ai on ai.agendamento_id = a.id and ai.tipo = 'principal'
    join public.servicos s on s.id = ai.servico_id
    where a.pacote_id is not null
      and a.status = 'Finalizado'
      and a.data_fim_real is not null
      and (p_unidade_id is null or a.unidade_id = p_unidade_id)
      and (p_transporte = 'todos' or (p_transporte = 'com' and a.tem_taxi = true) or (p_transporte = 'sem' and a.tem_taxi = false))
      and ((a.data_fim_real at time zone 'America/Sao_Paulo')::date) between p_data_inicio and p_data_fim
  )
  select servico, count(*) as qtd, avg(custo) as custo_unitario, sum(custo) as custo_total
  from itens
  group by servico
  order by custo_total desc;
$$;

